// ЗАЧЕМ. Продукт считает «сегодня» по МЕСТНОМУ дню (`toISODate` берёт
// getFullYear/getMonth/getDate). Это верно: человек сравнивает даты с
// тем, что видит в календаре у себя, а не в UTC.
//
// Но у прогона тоже есть местный день, и он разный: у меня Брюссель, у
