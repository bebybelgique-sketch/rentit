// Брюсселю бронь на сегодня уже дело»: `2026-09-21T01:00:00+02:00` —
// это 23:00 20-го по UTC, и в CI «сегодня» было 20-е. Локально зелено,
// в CI красно, код при этом правильный.
//
// Это ВТОРОЙ случай одного класса: локальные условия отличались от
// серверных. Первый — .env (закрыт envDir ниже). Лечится он одинаково:
// не подгонять тест, а сделать условия одинаковыми.
//
// Почему именно Брюссель, а не UTC. Продукт работает в Брабант-Валлоне,
// и поведение, которое проверяют тесты, — это поведение у бельгийца в
// браузере. Прогон в UTC проверял бы пользователя, которого нет.
//
// Ставится ДО загрузки конфигурации, чтобы значение досталось рабочим
// процессам. Что закрепление сработало — проверяет
// src/__tests__/timezone.test.ts: молча съехавший пояс вернул бы ровно
// ту же путаницу, только без объяснения.
