// src/hooks/useDocumentLanguage.ts
//
// Какой язык показывать. Один ответ на весь продукт.
//
// Зачем хук ради трёх строк: до 13.08 эта логика существовала в трёх местах.
// Навбар считал язык по-своему, а страницы «Условия» и «Политика
// конфиденциальности» держали СВОЙ `useState` и свой ряд кнопок — человек
// переключал язык в шапке, а юридический документ оставался на прежнем.
// Это был третий по счёту переключатель языка в продукте; два предыдущих
// свели 12.08, этот отсиделся внутри страниц.
//
// `startsWith`, а не `===`. `i18n.language` бывает `fr-BE`, `en-GB`,
// `nl-BE` — браузер отдаёт язык с регионом. Точное сравнение вернуло бы
// «язык не найден», и страница молча уехала бы во французский при выбранном
// нидерландском: без ошибки, без предупреждения, просто не тот текст.
//
// Падение во французский — правило продукта: он французский, и честнее
// показать французский, чем английский посреди французской страницы.

import { useTranslation } from 'react-i18next'
import { LANGUAGES, type Language } from '../i18n-next'

export function useDocumentLanguage(): Language {
  const { i18n } = useTranslation()
  return LANGUAGES.find(l => i18n.language?.startsWith(l)) ?? 'fr'
}
