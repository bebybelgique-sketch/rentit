// src/hooks/useCatalogHasItems.ts
import { useQuery } from '@tanstack/react-query';
import { itemKeys } from '../lib/queryKeys';
import { supabase } from '../lib/supabase';

/**
 * Есть ли в каталоге хоть одна доступная вещь — БЕЗ фильтров витрины.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ВОПРОС. Витрина умеет отвечать только «по этим фильтрам
 * ничего». Из её пустого ответа продукт до сих пор делал вывод «нет в этой
 * зоне» и предлагал расширить радиус. Замер прода 17.09.2026 показал, чем это
 * оборачивается: вещей в базе НОЛЬ, `browse_items` возвращает [] при любых
 * фильтрах. То есть заголовок «Aucun outil dans cette zone» был неправдой —
 * дело не в зоне, — а кнопка «Élargir à 50 km» вела во второй такой же пустой
 * экран.
 *
 * Отличить два состояния можно только запросом без фильтров. Он же чинит и
 * обратный случай: когда каталог наполнится, «не нашлось здесь» снова станет
 * правдой, и кнопка расширения вернётся сама — без правки кода.
 *
 * ПОЧЕМУ `head: true`. Нужно число, а не строки: запрос не тянет ни одной
 * колонки. RLS при этом действует, поэтому считается ровно то, что посетитель
 * и правда мог бы найти.
 *
 * ПОЧЕМУ `available`. Вопрос экрана — «есть ли что арендовать», а не «есть ли
 * что-нибудь в таблице». Владелец, скрывший все свои вещи, для посетителя
 * неотличим от пустого каталога, и врать ему «нет в этой зоне» так же нельзя.
 */
const countAvailableItems = async (): Promise<number> => {
  const { count, error } = await supabase
    .from('items')
    .select('id', { count: 'exact', head: true })
    .eq('available', true);

  if (error) throw new Error(error.message);
  return count ?? 0;
};

export const useCatalogHasItems = () => {
  const query = useQuery<number, Error>({
    queryKey: itemKeys.anyExist,
    queryFn: countAvailableItems,
    // Пустота каталога меняется редко и переживает переходы между фильтрами:
    // пересчитывать её на каждое движение ползунка радиуса незачем.
    staleTime: 60_000,
  });

  return {
    ...query,
    /**
     * `undefined`, пока ответа нет или запрос отказал. Намеренно НЕ `false`:
     * «каталог пуст» — сильное утверждение, и делать его из неотвеченного
     * запроса значит показать человеку неправду при первом же сбое сети.
     * Вызывающий на `undefined` показывает прежний текст, который верен всегда.
     */
    catalogIsEmpty: query.isSuccess ? query.data === 0 : undefined,
  };
};
