import { useEffect } from 'react'

/**
 * Заголовок вкладки — свой на каждом экране.
 *
 * ЗАЧЕМ. До 21.09 у продукта был ОДИН заголовок на всё: «RentIt —
 * Location d'outils entre voisins en Brabant Wallon» висел и на витрине,
 * и в кабинете, и на странице конкретной вещи. Это не косметика:
 *
 *   • семь открытых вкладок выглядят одинаково, и найти среди них нужную
 *     нельзя иначе как перебором;
 *   • история браузера и закладки хранят ту же строку семь раз — то есть
 *     не хранят ничего;
 *   • программа чтения с экрана объявляет при переходе название
 *     документа. Одинаковое название означает, что перехода не было.
 *
 * ЧЕГО ЭТОТ ХУК НЕ ДЕЛАЕТ И НЕ МОЖЕТ. Превью ссылки на конкретную вещь
 * он не меняет. `og:*` читают сборщики превью, которые JavaScript НЕ
 * ВЫПОЛНЯЮТ: Facebook, WhatsApp и Telegram видят исходный index.html и
 * ничего больше. Дописывать сюда обновление og-тегов значило бы сделать
 * вид, что починили, — превью у всех осталось бы общим. Настоящее
 * решение — отдавать шапку с сервера, и это отдельная работа.
 *
 * Google, в отличие от них, страницу выполняет и заголовок отсюда видит.
 */

/** Имя продукта в конце заголовка. Одно место, чтобы не разъехалось. */
const SUFFIX = 'RentIt'

/**
 * Заголовок по умолчанию — тот, что стоит в index.html.
 *
 * Считывается ОДИН РАЗ при загрузке модуля, до того как любой экран
 * успел его поменять. Взятый позже, он оказался бы заголовком случайной
 * страницы, и возврат «к умолчанию» возвращал бы неизвестно куда.
 */
const DEFAULT_TITLE = typeof document !== 'undefined' ? document.title : SUFFIX

/**
 * Поставить заголовок страницы.
 *
 * @param title Название экрана БЕЗ имени продукта: оно добавится само.
 *              `null` или пустая строка — экран ещё не знает, как
 *              называется (грузится вещь), и заголовок не трогаем: мигать
 *              «RentIt → Chargement → Perceuse» хуже, чем подождать.
 */
export function usePageTitle(title: string | null | undefined): void {
  useEffect(() => {
    if (!title) return

    const previous = document.title
    document.title = title === SUFFIX ? title : `${title} · ${SUFFIX}`

    // Возврат прежнего значения, а не умолчания: экраны бывают вложенными,
    // и снятие верхнего обязано открывать тот, что под ним.
    return () => {
      document.title = previous
    }
  }, [title])
}

/**
 * Оставить заголовок из index.html.
 *
 * Для входа: там написана маркетинговая строка, адресованная поисковику
 * и превью ссылки. Скопировать её в словари значило бы завести вторую
 * запись того же текста — и развести их при первой правке одной из двух.
 *
 * Зачем тогда вызывать хук вообще, если можно ничего не делать? Затем,
 * что экран, пришедший ПОСЛЕ другого, обязан заголовок перебить. Без
 * этого вызова возврат на вход с любой страницы оставлял бы в заголовке
 * её название.
 */
export function useDefaultPageTitle(): void {
  useEffect(() => {
    const previous = document.title
    document.title = DEFAULT_TITLE
    return () => {
      document.title = previous
    }
  }, [])
}

export { DEFAULT_TITLE, SUFFIX }
