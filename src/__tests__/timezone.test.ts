import { describe, it, expect } from 'vitest'
import { toISODate } from '../domain/availability'

/**
 * ПОЯС ПРОГОНА ЗАКРЕПЛЁН, И ЭТО ПРОВЕРЯЕТСЯ.
 *
 * ── ЗАЧЕМ ────────────────────────────────────────────────────────────
 *
 * Продукт считает «сегодня» по МЕСТНОМУ дню: `toISODate` берёт
 * getFullYear/getMonth/getDate. Это верно — человек сравнивает даты с
 * тем, что видит в своём календаре, а не в UTC.
 *
 * Но у прогона тоже есть местный день. 21.09.2026 тест «в час ночи по
 * Брюсселю бронь на сегодня уже дело» прошёл на моей машине и упал в CI:
 * `2026-09-21T01:00:00+02:00` — это 23:00 20-го по UTC, и у раннера
 * «сегодня» было 20-е. Код при этом правильный; разными были условия.
 *
 * Пояс закреплён в vitest.config.ts. Закрепление, которое молча
 * перестало работать, вернуло бы ту же путаницу — только уже без
 * объяснения, потому что причину все забыли. Поэтому проверка здесь:
 * она называет причину в момент поломки.
 *
 * ── ПОЧЕМУ НЕ ПРОСТО ПЕРЕПИСАТЬ ТОТ ТЕСТ ─────────────────────────────
 *
 * Можно было бы построить `now` из местных частей и не зависеть от
 * пояса вовсе. Тогда тест перестал бы падать — и перестал бы проверять
 * ровно то, ради чего написан: что полночь в Брюсселе и полночь в UTC
 * это разные моменты, и продукт обязан жить по первой.
 */

describe('часовой пояс прогона', () => {
  it('закреплён на Брюсселе', () => {
    // Смещение в минутах, со знаком наоборот: летом в Брюсселе UTC+2,
    // и getTimezoneOffset даёт -120.
    const summer = new Date('2026-07-01T12:00:00Z').getTimezoneOffset()
    const winter = new Date('2026-01-01T12:00:00Z').getTimezoneOffset()

    expect(
      { summer, winter },
      'прогон идёт не в бельгийском поясе — проверьте process.env.TZ в vitest.config.ts',
    ).toEqual({ summer: -120, winter: -60 })
  })

  it('переход на летнее время учитывается, а не зашит числом', () => {
    // Если бы пояс был задан фиксированным смещением (UTC+2), зима
    // совпала бы с летом. Здесь они обязаны различаться.
    const summer = new Date('2026-07-01T12:00:00Z').getTimezoneOffset()
    const winter = new Date('2026-01-01T12:00:00Z').getTimezoneOffset()
    expect(summer).not.toBe(winter)
  })

  /**
   * Прямая связь с тем, что сломалось: `toISODate` обязан отдавать
   * БЕЛЬГИЙСКИЙ календарный день, а не день по Гринвичу.
   */
  it('час ночи по Брюсселю — это уже новый день, а не прошлый', () => {
    expect(toISODate(new Date('2026-09-21T01:00:00+02:00'))).toBe('2026-09-21')
  })

  it('23:30 по Брюсселю — ещё прежний день', () => {
    expect(toISODate(new Date('2026-09-21T23:30:00+02:00'))).toBe('2026-09-21')
  })
})
