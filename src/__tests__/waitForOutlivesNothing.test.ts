import { describe, it, expect } from 'vitest';
import { getConfig } from '@testing-library/react';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Ожидание внутри теста не должно сдаваться раньше, чем сам тест.
 *
 * У `waitFor` свой таймаут (по умолчанию 1000 мс), у vitest свой (5000 мс).
 * Пока первый вчетверо меньше второго, проверка объявляет провал задолго
 * до того, как тест признают зависшим, — и на загруженной машине это даёт
 * красный без повода. Ровно так 19.09 упал `useBrowseItems > точка
 * посетителя`: один раз в полном наборе, и ни в одиночку, ни на повторе
 * всего набора не воспроизвёлся.
 *
 * Мерцающий гейт перестают читать целиком, и настоящее падение тонет в нём.
 */
describe('таймаут ожидания', () => {
  const VITEST_DEFAULT_TEST_TIMEOUT = 5000;

  it('больше секунды — иначе красное мерцание под нагрузкой', () => {
    expect(getConfig().asyncUtilTimeout).toBeGreaterThan(1000);
  });

  // Верхняя граница — не придирка. Если ожидание переживёт сам тест,
  // зависание перестанет отличаться от медленного рендера, и настройка из
  // лекарства станет глушителем.
  it('меньше таймаута теста — иначе зависание спрячется', () => {
    expect(getConfig().asyncUtilTimeout).toBeLessThan(VITEST_DEFAULT_TEST_TIMEOUT);
  });

  // Число выше взято из умолчания vitest. Если его однажды зададут в
  // конфиге, проверка должна об этом узнать, а не рассуждать о старом.
  it('таймаут теста в конфиге не переопределён — сравнение выше честное', () => {
    const cfg = readFileSync(join(process.cwd(), 'vitest.config.ts'), 'utf8');
    expect(cfg, 'testTimeout задан явно — сверить с ним asyncUtilTimeout')
      .not.toMatch(/testTimeout\s*:/);
  });
});
