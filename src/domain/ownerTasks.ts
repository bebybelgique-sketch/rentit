// ЧТО ЖДЁТ ХОДА ВЛАДЕЛЬЦА. Одно определение на весь продукт.
//
// ── ЗАЧЕМ ЭТОТ ФАЙЛ ──────────────────────────────────────────────────
//
// В комментарии к `supabase/functions/notify-rental` цена молчания
// названа прямо: «сосед оставляет запрос, владелец не получает письма,
// оба видят „всё прошло“, и площадка молча умирает для обоих».
//
// Экран «À faire maintenant» в /my-items это наполовину чинил — но
// увидеть его можно, только УЖЕ ОТКРЫВ тот экран. Человек, у которого
// есть дело, узнаёт о нём, зайдя проверить, нет ли у него дела.
//
// И чинил наполовину буквально: там считался ОДИН вид дела —
// неотвеченная заявка. Передача вещи и приём возврата лежали в
// /my-rentals под вкладкой, без единого признака срочности, хотя
// просроченный возврат держит вещь занятой и бьёт по следующей брони.
//
// ── ЧТО СЧИТАЕТСЯ ДЕЛОМ ──────────────────────────────────────────────
//
// ДЕЛО — ЭТО КОГДА ДРУГОЙ ЧЕЛОВЕК ЖДЁТ ТВОЕГО ХОДА В ПРИЛОЖЕНИИ.
//
// Определение узкое намеренно, и вот против чего оно стоит. Счётчик,
// который считает «всё, что можно сделать», набирает постоянное число и
// перестаёт значить что-либо через неделю: человек привыкает к красному
// кружку и больше его не видит. Счётчик, который обязан обнуляться,
// работает — но только если каждое его слагаемое действительно уходит.
//
// Отсюда три следствия, каждое проверяется в наборе:
//
//   • ОТЗЫВ — НЕ ДЕЛО. Аренда закончена, никто никого не ждёт. Отзыв не
//     сгорает и никого не держит; он останется висеть навсегда у того,
//     кто отзывы не пишет, и обнулиться счётчику будет не с чего.
//   • ПОДТВЕРЖДЁННАЯ БРОНЬ НА СЛЕДУЮЩИЙ МЕСЯЦ — НЕ ДЕЛО СЕГОДНЯ.
//     Передавать нечего, пока не наступил день начала.
//   • ОТМЕНЁННОЕ, ОТКЛОНЁННОЕ И СГОРЕВШЕЕ — не дело никогда.
//
// ── ПОЧЕМУ ТОЛЬКО ВЛАДЕЛЕЦ ───────────────────────────────────────────
//
// Это не упущение, а свойство продукта. Посмотрите на правила переходов
// в `supabase/functions/transition-booking`: после того как заявка
// принята, ВСЕ действия принадлежат владельцу — `handover` (owner),
// `complete` (owner). Арендатору доступна одна `cancel`, и это его
// право, а не обязанность: никто не ждёт, когда он ею воспользуется.
//
// Арендатору нужно другое — ИЗВЕСТИЕ: «вашу заявку приняли». Известие не
// дело: у него нет действия, которое его закрывает, зато есть состояние
// «прочитано», которого в базе нет. Сводить одно к другому значило бы
// завести счётчик, который у арендатора никогда не обнуляется.

import { answerDeadline, isUrgent, type RequestDeadline } from './requestDeadline'
import { toISODate } from './availability'

export type OwnerTaskKind =
  /** Пришла заявка. Сгорает через 24 часа (см. requestDeadline). */
  | 'answer'
  /** День начала наступил: вещь пора отдать. */
  | 'handover'
  /** Срок аренды кончился: пора принять возврат и закрыть бронь. */
  | 'complete'

/** Бронь в том виде, в каком её отдаёт useOwnerItems. */
export interface TaskBooking {
  readonly id: string
  readonly status: string | null
  readonly start_date: string | null
  readonly end_date: string | null
  readonly created_at: string | null
}

export interface OwnerTask {
  readonly kind: OwnerTaskKind
  readonly bookingId: string
  /**
   * Срок ответа — ТОЛЬКО у заявки: двадцатичетырёхчасовое окно назначает
   * крон `expire-bookings`, и больше никакое дело не сгорает само.
   * У передачи и возврата срока нет — есть просрочка, и она в `overdueDays`.
   */
  readonly deadline?: RequestDeadline
  /** На сколько дней просрочено. 0 — наступило сегодня. */
  readonly overdueDays: number
  /** Требует внимания прямо сейчас — отличается видом, а не только числом. */
  readonly urgent: boolean
}

/**
 * Насколько день `date` (YYYY-MM-DD) в прошлом относительно `today`.
 *
 * СРАВНЕНИЕ СТРОКАМИ, А НЕ ДАТАМИ. `start_date` — это календарный день
 * без времени. `new Date('2026-09-21')` даёт полночь UTC, а «сегодня» у
 * человека — в его поясе; в Бельгии летом расхождение два часа, и
 * сравнение временных меток объявляло бы день начала наступившим на два
 * часа раньше либо позже, смотря в какую сторону. Формат YYYY-MM-DD
 * сравнивается лексикографически и совпадает с календарным порядком, а
 * `toISODate` берёт день в поясе самого человека.
 */
const daysPast = (date: string | null, today: string): number => {
  if (!date || date > today) return -1
  if (date === today) return 0
  // Разницу считаем уже датами: строки дают только ответ «раньше/позже».
  const ms = Date.parse(`${today}T00:00:00`) - Date.parse(`${date}T00:00:00`)
  return Number.isNaN(ms) ? -1 : Math.round(ms / 86_400_000)
}

/**
 * Сколько дней просрочки делают возврат срочным.
 *
 * Ноль: просроченный возврат срочен в тот же день. Вещь числится занятой,
 * и следующая заявка на неё упрётся в занятые даты — то есть молчание
 * владельца здесь стоит не вежливости, а второй аренды.
 */
const HANDOVER_URGENT_FROM_DAY = 0

/**
 * Дело по одной брони — или ничего.
 *
 * `now` передаётся, а не берётся изнутри: функция обязана проверяться без
 * подмены часов процесса.
 */
export const taskFor = (booking: TaskBooking, now: Date): OwnerTask | null => {
  const today = toISODate(now)

  switch (booking.status) {
    case 'pending_approval': {
      const deadline = answerDeadline(booking.created_at ?? null, now)
      return {
        kind: 'answer',
        bookingId: booking.id,
        deadline,
        overdueDays: deadline.state === 'overdue' ? 1 : 0,
        urgent: isUrgent(deadline),
      }
    }

    case 'confirmed': {
      // Пока день начала не наступил, отдавать нечего. Считать такую
      // бронь делом значило бы держать в счётчике единицу месяцами.
      const past = daysPast(booking.start_date, today)
      if (past < 0) return null
      return {
        kind: 'handover',
        bookingId: booking.id,
        overdueDays: past,
        urgent: past >= HANDOVER_URGENT_FROM_DAY,
      }
    }

    case 'active': {
      const past = daysPast(booking.end_date, today)
      if (past < 0) return null
      return {
        kind: 'complete',
        bookingId: booking.id,
        overdueDays: past,
        urgent: past >= HANDOVER_URGENT_FROM_DAY,
      }
    }

    // Остальные статусы дела не создают, и это перечислено поимённо, а не
    // отдано `default`, чтобы новое значение в enum `booking_status`
    // заметил человек, а не счётчик молча.
    case 'completed':       // аренда закрыта; отзыв делом не считается — см. шапку
    case 'cancelled':
    case 'rejected':
    case 'expired':
    case 'payment_expired':
    case 'pending_payment': // платежей в продукте нет
    case 'disputed':        // спор ведётся не кнопкой в списке
      return null

    default:
      // Неизвестный статус не создаёт дела и не роняет экран. Выдумать
      // здесь задачу хуже, чем её не показать: человек пойдёт нажимать
      // кнопку, которой нет.
      return null
  }
}

/** Порядок видов дел при равной срочности: сначала то, что сгорает. */
const KIND_ORDER: Record<OwnerTaskKind, number> = {
  answer: 0,
  complete: 1,
  handover: 2,
}

/**
 * Все дела владельца, в порядке «чем скорее, тем выше».
 *
 * Сортировка: сначала срочные, потом по виду, потом по глубине просрочки.
 * Список из восьми дел глазами по числам не читают — поэтому порядок, а
 * не только подписи.
 */
export const ownerTasks = (bookings: readonly TaskBooking[], now: Date): OwnerTask[] =>
  bookings
    .map((b) => taskFor(b, now))
    .filter((t): t is OwnerTask => t !== null)
    .sort((a, b) =>
      Number(b.urgent) - Number(a.urgent) ||
      KIND_ORDER[a.kind] - KIND_ORDER[b.kind] ||
      b.overdueDays - a.overdueDays)

/**
 * Сколько дел ждёт человека. Это число и показывает значок в навигации.
 *
 * Отдельная функция, а не `ownerTasks(...).length` по месту: значок живёт
 * в навигации, список — на экране дел, и считать их двумя разными
 * способами значило бы завести расхождение между «3» в кружке и двумя
 * строками под ним.
 */
export const ownerTaskCount = (bookings: readonly TaskBooking[], now: Date): number =>
  ownerTasks(bookings, now).length
