//
// ПОЧЕМУ ОНИ ЖИВУТ ЗДЕСЬ, А НЕ В vite.config.ts. Сторож оболочки
// (src/__tests__/shell.test.ts) обязан проверять то, что РЕАЛЬНО уезжает
// посетителю. Если бы он повторял логику своей копией, разошлись бы они
// в первый же раз, когда правку внесли в одно место из двух, — и сторож
// продолжал бы гореть зелёным про страницу, которой больше нет.
//
// Плагин в vite.config.ts — тонкая обёртка над этими функциями.

/**
 * Подставить адрес сайта вместо `%SITE_URL%`.
 *
 * `replace` с флагом g, а не `replaceAll`: целевая библиотека проекта
 * ниже es2021, и `replaceAll` роняет tsc. Менять цель компиляции ради
 * одной строки значит трогать сборку целиком — несоразмерно поводу.
 */
export const injectSiteUrl = (html: string, siteUrl: string): string =>
  html.replace(/%SITE_URL%/g, siteUrl)

/**
 * Снять комментарии.
 *
 * В шапке index.html живут длинные пояснения по-русски: почему снят
 * unpkg, почему из описания убрано обещание страховки, почему превью
 * растровое. Для того, кто откроет репозиторий, они и написаны — там
 * причина, без которой правку повторят обратно.
 *
 * Но посетителю они не нужны, а скачивал их каждый: полтора килобайта
 * внутренней переписки в каждой загрузке. Вместе с ними наружу уезжало
 * и имя чужого домена — единственное упоминание `rentit.be`, оставшееся
 * в собранной странице, было в объяснении, почему его там больше нет.
 *
 * `<!--[if` не трогаем: условные комментарии — это не комментарии, а
 * инструкции старым браузерам. В продукте их сейчас нет, но правило
 * дешевле объяснения, почему однажды пропала совместимость.
 */
export const stripHtmlComments = (html: string): string =>
  html.replace(/\n?[ \t]*<!--(?!\[if)[\s\S]*?-->/g, '').replace(/\n{3,}/g, '\n\n')
