// Снимки объявления: одно место, где `photos` превращается в список ссылок.
//
// ЗАЧЕМ. В таблице `items` колонка `photos` — это `jsonb`, а не массив
// строк. Пока типы писались руками, приложение объявляло её `string[]` и
// верило себе на слово; после `supabase gen types` она станет `Json` —
// рекурсивным объединением, у которого нет ни `[0]`, ни `.map`. Каждое
// место, читающее снимки, превратится в ошибку компиляции, и соблазн будет
// один: расставить `as string[]` по компонентам. Это вернуло бы ровно то
// состояние, из которого мы уходим, — «тип говорит одно, база отдаёт
// другое», только теперь с подписью компилятора.
//
// Поэтому проверка одна и живёт здесь. Заодно она отвечает на вопрос,
// который в `jsonb` возникает по-настоящему: в массиве может лежать что
// угодно, включая null и объекты, — такие элементы отбрасываются, а не
// доезжают в `src` картинки пустой строкой.

/** Что угодно, у чего может быть поле `photos`: строка базы, строка RPC, снимок формы. */
export interface WithPhotos {
  photos?: unknown;
}

/**
 * Ссылки на снимки — только те, что действительно строки.
 *
 * Пустой список — законный ответ: объявление без фотографий существует, и
 * показывать вместо него заглушку решает уже вызывающий.
 */
export function photosOf(source: WithPhotos | null | undefined): string[] {
  const raw = source?.photos;
  if (!Array.isArray(raw)) return [];
  return raw.filter((p): p is string => typeof p === 'string' && p.length > 0);
}

/**
 * Первый снимок или `null`.
 *
 * Прежде эту роль играло поле `image_url` в типе `Item` — поле, которого в
 * базе нет. Его вычисляли в трёх хуках тремя одинаковыми строчками, а
 * форма редактирования однажды отправила его в UPDATE, и PostgREST
 * отклонил ЗАПРОС ЦЕЛИКОМ (PGRST204): страница не сохраняла ни цену, ни
 * описание. Выдуманное поле в типе рано или поздно уезжает в запрос.
 */
export function coverPhoto(source: WithPhotos | null | undefined): string | null {
  return photosOf(source)[0] ?? null;
}

// ---------------------------------------------------------------------------
// История вещи: результат RPC `item_history` (миграция 20260817000023).
//
// Функция объявлена `RETURNS jsonb`, то есть после `supabase gen types` её
// возврат станет `Json` — ровно как `photos`. До сих пор страница вещи брала
// его приведением (`historyData as ItemHistory`): приведение молча обещает
// компилятору форму, которой никто не проверял, и на любом расхождении даёт
// не отказ, а «Invalid Date» в тексте про доверие к владельцу.
// ---------------------------------------------------------------------------

/** Сколько раз вещь брали и когда вернули в последний раз. */
export interface ItemHistory {
  times_rented: number;
  /** Дата ВОЗВРАТА (YYYY-MM-DD) или null, если вещь ещё не сдавали. */
  last_rented: string | null;
}

/**
 * Разбор ответа `item_history`. `null` — сведений нет; вызывающий тогда не
 * показывает блок вовсе, а не рисует «сдавали 0 раз».
 */
export function itemHistoryOf(raw: unknown): ItemHistory | null {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null;
  const r = raw as Record<string, unknown>;
  // count(*) из jsonb приходит числом; дробное или отрицательное значение
  // означало бы, что мы читаем не то поле.
  const times = typeof r.times_rented === 'number' && Number.isInteger(r.times_rented) && r.times_rented >= 0
    ? r.times_rented
    : 0;
  // Дата нужна ровно в виде YYYY-MM-DD: страница дописывает к ней
  // 'T00:00:00' и строит Date. Всё остальное — пустота, а не «Invalid Date»
  // посреди фразы.
  const last = typeof r.last_rented === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(r.last_rented)
    ? r.last_rented
    : null;
  return { times_rented: times, last_rented: last };
}
