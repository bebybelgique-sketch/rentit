import { useEffect, useRef, useState } from 'react'
import { useLocation } from 'react-router-dom'

/**
 * Смена экрана становится заметной тому, кто не смотрит на экран.
 *
 * ── ЧТО ИМЕННО СЛОМАНО В ЛЮБОМ SPA ───────────────────────────────────
 *
 * На обычном сайте переход по ссылке грузит новый документ, и браузер
 * сам объявляет его название, ставит фокус в начало и сбрасывает
 * прокрутку. В одностраничном приложении не происходит НИЧЕГО из этого:
 * меняется только разметка.
 *
 * Замер 21.09.2026 по собственной сборке:
 *
 *     фокус до перехода:  "RentIt"
 *     фокус после:        "Parcourir" <A>
 *
 * То есть после перехода фокус остался на НАЖАТОЙ ССЫЛКЕ. Для человека
 * на программе чтения с экрана это значит: он нажал, и ничего не
 * сообщили. Следующий Tab уводит его по остаткам навигации, а не в
 * содержимое, которое он открыл.
 *
 * ── ПОЧЕМУ ДВА ДЕЙСТВИЯ, А НЕ ОДНО ───────────────────────────────────
 *
 * 1. ОБЪЯВЛЕНИЕ. Живая область (`aria-live`) произносит название нового
 *    экрана. Берём его из `document.title`, который ставит usePageTitle:
 *    второго источника названия заводить нельзя — разойдутся.
 *
 * 2. ФОКУС. Переносится на заголовок содержимого. Без этого объявление
 *    прозвучит, а клавиатура останется в старом месте.
 *
 * Одного из двух не хватает: объявление без переноса фокуса оставляет
 * человека в навигации, перенос без объявления — молча роняет его в
 * незнакомое место.
 *
 * ── ПОЧЕМУ НЕ НА ПЕРВОЙ ЗАГРУЗКЕ ─────────────────────────────────────
 *
 * При первом открытии документ объявляет браузер сам. Продублировать —
 * значит сказать название дважды подряд.
 */

/**
 * Заголовок ставится эффектом ПОСЛЕ отрисовки, поэтому в момент смены
 * адреса `document.title` ещё прежний. Ждём кадр.
 */
const TITLE_SETTLE_MS = 120

export default function RouteAnnouncer() {
  const { pathname } = useLocation()
  const [message, setMessage] = useState('')
  const first = useRef(true)

  useEffect(() => {
    if (first.current) {
      first.current = false
      return
    }

    const timer = window.setTimeout(() => {
      setMessage(document.title)

      // Фокус — на область содержимого. `tabIndex={-1}` делает её
      // фокусируемой программно, не добавляя лишней остановки при обходе
      // клавиатурой.
      const main = document.getElementById('main-content')
      main?.focus()

      // Прокрутка вверх. В SPA она тоже не сбрасывается сама: человек,
      // открывший вещь из середины длинного списка, попадал на новую
      // страницу, прокрученную вниз.
      window.scrollTo(0, 0)
    }, TITLE_SETTLE_MS)

    return () => window.clearTimeout(timer)
  }, [pathname])

  return (
    <div
      aria-live="polite"
      aria-atomic="true"
      // Не `display: none` и не `visibility: hidden`: скрытое таким
      // образом содержимое программы чтения НЕ ПРОИЗНОСЯТ. Область
      // обязана остаться в потоке и при этом не занимать места.
      className="visually-hidden"
    >
      {message}
    </div>
  )
}
