import { useTranslation } from 'react-i18next'

/**
 * Значок «столько дел ждёт тебя».
 *
 * ── КОГДА ЕГО НЕТ ────────────────────────────────────────────────────
 *
 * При нуле — НИЧЕГО, а не кружок с нулём. Пустой значок занимает то же
 * место и приучает глаз его не замечать: к тому времени, когда там
 * появится единица, человек уже перестал туда смотреть.
 *
 * ── ЦВЕТ ─────────────────────────────────────────────────────────────
 *
 * Красный #C8102E, и это тот самый случай, ради которого он в палитре
 * оставлен. Правило продукта (шапка src/index.css): красный означает
 * ДЕЙСТВИЕ, то, что жмут. Здесь он означает ровно это — дело, которое
 * ждёт хода. Жёлтый-сигнал сюда не годится: он живёт только на тёмном, а
 * значок висит и на светлой странице, где даёт контраст 1.44:1.
 *
 * ── ПОЧЕМУ ЧИСЛО, А НЕ ТОЧКА ─────────────────────────────────────────
 *
 * Точка говорит «что-то есть». Число говорит, сколько времени это
 * займёт, — а между «одна заявка» и «шесть» разница в том, откроет
 * человек приложение сейчас или вечером.
 *
 * Больше девяти показываем как «9+»: трёхзначное число в кружке
 * нечитаемо, а разницы между 12 и 40 делами для решения «открыть сейчас»
 * уже нет.
 */

const MAX_SHOWN = 9

interface TaskBadgeProps {
  count: number
  /** `nav` — в строке навигации, `tab` — поверх значка нижней панели. */
  placement?: 'nav' | 'tab'
  /**
   * Подпись для программы чтения. По умолчанию — «N choses à faire»; у
   * колокольчика ленты свои слова: там не дела, а непрочитанное.
   */
  label?: string
}

export default function TaskBadge({ count, placement = 'nav', label }: TaskBadgeProps) {
  const { t } = useTranslation()

  if (count <= 0) return null

  const shown = count > MAX_SHOWN ? `${MAX_SHOWN}+` : String(count)

  return (
    <span
      className={`task-badge task-badge-${placement}`}
      // Число само по себе — просто цифра рядом со словом. Вслух его
      // читают как часть подписи, и без пояснения выходит «Mes outils 3».
      aria-label={label ?? t('tasks.badgeLabel', { count })}
      role="status"
    >
      {shown}
    </span>
  )
}
