/**
 * Экранирование для HTML писем. Обязательно для всего, что написал
 * человек: название вещи, имя, сообщение к заявке, причина отмены.
 *
 * До 01.10 notify-rental вставлял их в HTML как есть. Любой вошедший мог
 * написать в сообщении к заявке `</em></p><p><a href="…">Confirmez votre
 * compte</a>`, и владелец получал письмо С АДРЕСА ПЛОЩАДКИ с чужой кнопкой —
 * готовый фишинг под нашим именем. Тема письма — простой текст, её
 * экранировать не надо (иначе человек прочтёт «&amp;»).
 */
export function esc(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
