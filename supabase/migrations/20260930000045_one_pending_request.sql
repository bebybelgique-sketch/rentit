-- =============================================
-- 45. Одна ожидающая заявка на те же даты — правилом базы, а не проверкой
-- =============================================
--
-- ЧТО БЫЛО. request-rental спрашивал renter_has_pending_request (миграция 22,
-- раздел 9) и, услышав «нет», вставлял бронь. Это два отдельных запроса без
-- блокировки: два одинаковых запроса, пришедших одновременно, оба слышали
-- «нет» и оба вставляли — две заявки на одну вещь и одни даты, два письма и
-- два push владельцу. Путь реальный: кнопка «отправить» снова активна после
-- сетевой ошибки, а сервер к тому моменту заявку уже записал; или две
-- вкладки. Вдобавок ошибку самой проверки функция не читала: при сбое
-- проверка молча пропускала дубль.
--
-- ЧТО СТАЛО. То же правило — ограничением исключения на bookings. Его держит
-- индекс: второй одновременный INSERT ждёт первого и получает 23P01, а
-- request-rental переводит этот код в duplicate_request.
--
-- ПРАВИЛО ОСТАЁТСЯ ОДНО. Функция renter_has_pending_request удаляется здесь
-- же: её звал только request-rental, а две копии одного условия — ровно то,
-- от чего уходила миграция 22. Заодно закрывается побочный путь: функцию с
-- SECURITY DEFINER мог позвать любой вошедший и узнать, ждёт ли ЧУЖОЙ
-- арендатор ответа по вещи на эти даты.
--
-- ПЕРЕСЕЧЕНИЕ ДАТ ЗДЕСЬ — НЕ ЗАНЯТОСТЬ ВЕЩИ. Занятость по-прежнему считает
-- только unavailable_days; это правило про одного арендатора (раздел 9
-- миграции 22 так и говорит). Исключение для этого файла записано в
-- scripts/check-availability-single-source.mjs.
--
-- ДАННЫЕ. Проверено на проде 30.09 до применения: пар ожидающих заявок
-- одного арендатора на пересекающиеся даты одной вещи — 0. Будь они, ALTER
-- TABLE упал бы целиком и ничего бы не изменил.
--
-- ПРОВЕРКА ПОСЛЕ ПРИМЕНЕНИЯ — `npm run test:edge`: вторая заявка на те же
-- даты → 409 duplicate_request; две одновременные → ровно одна бронь.
-- =============================================

-- Равенство по uuid в индексе GiST даёт только btree_gist.
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;

ALTER TABLE public.bookings
  DROP CONSTRAINT IF EXISTS bookings_one_pending_request;

ALTER TABLE public.bookings
  ADD CONSTRAINT bookings_one_pending_request
  EXCLUDE USING gist (
    item_id   WITH =,
    renter_id WITH =,
    daterange(start_date, end_date, '[]') WITH &&
  ) WHERE (status = 'pending_approval');

DROP FUNCTION IF EXISTS public.renter_has_pending_request(uuid, uuid, date, date);
