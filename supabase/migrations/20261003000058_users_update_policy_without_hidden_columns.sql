-- =============================================
-- 58. Профиль снова сохраняется: политика UPDATE на users без подзапросов
--     к скрытым колонкам
-- =============================================
--
-- ЧТО СЛОМАНО. Миграция 43 (24.09) закрыла от клиента колонки
-- referral_code и referred_by (revoke select). А политика «Users can
-- update own safe fields» в WITH CHECK сверяла referred_by подзапросом
-- (SELECT u.referred_by FROM users u …) — от лица вошедшего. Подзапрос
-- падает с 42501, а вместе с ним ЛЮБОЕ сохранение профиля: имя, фото,
-- деревня, координаты.
--
-- Проверено на проде 03.10, с откатом: UPDATE full_name и avatar_url ТЕМИ
-- ЖЕ значениями от роли authenticated → «permission denied for table
-- users». Без фото профиля выкладка вещи закрыта (ListItem). Значит, с
-- 24.09 новый человек не мог выложить ни одной вещи. Сквозные проверки
-- этого не видели: у их учёток фото и имя стоят с августа, путь
-- сохранения они не проходят.
--
-- ПОЧЕМУ ПОДЗАПРОСЫ НЕ НУЖНЫ. Что вошедший может менять, решают
-- колоночные права (миграция 17): табличного UPDATE у authenticated нет,
-- колоночный — только на avatar_url, full_name, village, lat, lng.
-- Попытка тронуть role, is_pro, рейтинги, телефон или реферальные поля
-- падает на правах, до политики дело не доходит. Подзапросы в WITH CHECK
-- дублировали эту границу — и сломались, как только часть колонок стала
-- нечитаемой. Колоночные права держит сторож
-- scripts/check-migration-grants.mjs.
--
-- Политика остаётся о главном: менять можно только СВОЮ строку.
-- =============================================

DROP POLICY IF EXISTS "Users can update own safe fields" ON public.users;

CREATE POLICY "Users can update own safe fields" ON public.users
  FOR UPDATE TO authenticated
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id);
