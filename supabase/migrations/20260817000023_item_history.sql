-- =============================================
-- RentIt: история вещи
--
-- Единственная позиция, оставшаяся из разбора Booqable: показать на
-- странице вещи, сколько раз её уже брали и когда в последний раз.
--
-- Зачем: доверие строится из данных, которые УЖЕ есть. Отзывы appear
-- редко — человек, довольный дрелью, не идёт писать рецензию, — а факт
-- «эту вещь брали семь раз» лежит в базе сам собой и не требует от
-- сторон ни одного лишнего действия.
--
-- Что отдаётся наружу: два числа. Ни кто арендовал, ни на какую сумму,
-- ни на какие даты. Это агрегат, и он слабее того, что уже публично
-- через unavailable_days (там видно занятые дни поимённо по датам).
--
-- SECURITY DEFINER по той же причине, что у items_busy_between: политики
-- на bookings пускают к броне только её стороны, поэтому посторонний
-- своими глазами историю не увидит.
--
-- ⚠️ Считаются ТОЛЬКО завершённые брони (`completed`). Отменённые,
-- отклонённые и истёкшие — не история сдачи, а её отсутствие; включать
-- их значило бы завышать число тем сильнее, чем хуже работает владелец.
--
-- ПРИМЕНЯТЬ: npx supabase db query --linked -f этот_файл.sql
-- НЕ `supabase db push`.
-- =============================================

CREATE OR REPLACE FUNCTION public.item_history(p_item_id uuid)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT jsonb_build_object(
    'times_rented', count(*),
    -- Дата ВОЗВРАТА, а не начала: «последний раз в июле» про то, когда
    -- вещь вернулась в оборот.
    'last_rented',  max(b.end_date)
  )
  FROM public.bookings b
  WHERE b.item_id = p_item_id
    AND b.status  = 'completed';
$$;

GRANT EXECUTE ON FUNCTION public.item_history(uuid) TO anon, authenticated;

