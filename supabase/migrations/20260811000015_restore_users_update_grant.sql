-- RentIt: вернуть право записи в свой профиль
--
-- Найдено 11.08 сквозной проверкой на проде, а не чтением кода.
-- PATCH /rest/v1/users отвечает 403:
--   {"code":"42501","message":"permission denied for table users"}
--
-- 42501 — это отказ на уровне GRANT, а не RLS. Политика
-- "Users can update own safe fields" (миграция 08) на месте и написана
-- верно, но до неё дело не доходит: роль authenticated вообще не имеет
-- UPDATE на public.users, и Postgres отказывает раньше проверки политики.
--
-- Откуда взялось. Миграция 07 сняла табличный грант на чтение
-- (REVOKE SELECT ON public.users) и выдала взамен поимённый список
-- столбцов. Право записи она не выдавала — в комментарии стояло
-- «INSERT / UPDATE / DELETE remain unrestricted at column level
-- (row-level RLS policies handle those)». Это верно лишь пока табличный
-- грант на запись существует; в текущей базе его нет. Миграция 08 затем
-- сняла UPDATE с трёх служебных столбцов, что на пустом месте ничего не
-- изменило.
--
-- Чем это стоило продукту. Аватар не сохраняется ни у кого. ListItem
-- (src/pages/ListItem.tsx) не показывает форму, пока в users пусто в
-- avatar_url, — значит НИ ОДИН новый пользователь не может выложить
-- инструмент. Воронка закрыта на первом шаге, и цикл аренды непроверяем.
-- Пользователь при этом видит английскую строку Postgres поверх
-- французской страницы.
--
-- Почему поимённо, а не GRANT UPDATE на всю таблицу. Табличный грант
-- вернул бы к жизни дыру, которую закрывала миграция 08: столбцы
-- phone_otp, phone_otp_expires_at и stripe_customer_id снова стали бы
-- записываемыми с клиента. Перечисляем ровно то, что человек и правда
-- меняет о себе. Столбцы role, phone_verified, is_pro, рейтинги,
-- business_plan* и referred_by сюда НЕ входят: их и политика пришпиливает
-- к прежним значениям, и права теперь не дают их тронуть.
--
-- НЕ ПРИМЕНЕНО. Миграция написана как предложение: изменение прав в
-- публично доступной базе — решение Рамзана, и применяется его руками.
-- =============================================

GRANT UPDATE (
  full_name,
  avatar_url,
  phone,
  village,
  lat,
  lng
) ON public.users TO authenticated;

-- anon в список не входит намеренно: неаутентифицированный посетитель не
-- имеет своей строки, и auth.uid() = id для него никогда не истинно.

