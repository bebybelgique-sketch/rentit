-- =============================================
-- RentIt: телефон и домашние координаты закрыты от чтения
--
-- Найдено 11.08 стражем утверждений. Политика на users — "Public user
-- names/ratings visible" USING (true), а гранты столбцов позволяли
-- анониму читать phone, lat и lng. То есть один запрос к /rest/v1/users
-- отдавал телефоны и домашние координаты всех, кто их указал.
--
-- Политика конфиденциальности во всех трёх языках обещает обратное:
-- «Numéro de téléphone — contact entre locataires et propriétaires APRÈS
-- réservation confirmée». Обещание и права расходились.
--
-- Сегодня утечки не случилось только потому, что phone у единственной
-- учётки пуст. Первый же подтверждённый номер стал бы публичным.
--
-- RLS здесь не помогает: она работает построчно, а нужно закрыть
-- столбец. Поэтому REVOKE, а не политика.
--
-- Совместимость проверена: ни одна страница не читает эти столбцы.
-- Единственным потребителем был блок «Contacter via WhatsApp» на
-- странице вещи, который встраивал чужой телефон в ссылку wa.me и
-- показывал его любому посетителю. Он удалён тем же изменением.
--
-- phone_verified (булев признак) намеренно остаётся: это знак доверия
-- на карточке, и он не раскрывает сам номер.
-- =============================================

REVOKE SELECT (phone, lat, lng) ON public.users FROM anon;
REVOKE SELECT (phone, lat, lng) ON public.users FROM authenticated;

