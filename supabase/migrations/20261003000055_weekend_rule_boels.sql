-- =============================================
-- 55. Тариф «выходные»: правило Boels — пятница сверх пакета
-- =============================================
--
-- Схема не меняется — меняется расчёт (supabase/functions/_shared/
-- pricing.ts), и описание столбца обязано говорить то же, что код.
--
-- Было (#150, по образцу Kiloutou): пакет закрывал сб–вс, пт–вс, сб–пн и
-- пт–пн. У Kiloutou пятница — это 14–16 часов, а у нас бронь на пятницу —
-- весь день: владелец отдавал его даром. Внешнее ревью 03.10 (GPT): «пакет
-- не может покрывать будни бесплатно».
--
-- Стало (Boels, Бельгия): «samedi – lundi», до 48 часов — один дневной
-- тариф; «vendredi – lundi», до 72 часов — два. Пакет — сб–вс или сб–пн
-- (возврат в понедельник), пятница — отдельный день.
-- =============================================

COMMENT ON COLUMN public.items.price_weekend IS
  'Цена за выходные, евро: сб–вс или сб–пн (возврат в понедельник), по правилу Boels; пятница сверх пакета — отдельный день. NULL — тарифа нет. Расчёт — supabase/functions/_shared/pricing.ts.';
