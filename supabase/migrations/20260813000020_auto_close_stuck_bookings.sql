-- Бронь могла остаться живой навсегда. Завершить её из `active` вправе
-- только владелец («возврат состоялся»), у арендатора кнопки нет, и ни один
-- таймер до этих статусов не доходил: `expire-bookings` трогал только
-- `pending_approval`. Владелец забыл нажать — двое живых людей ждут друг
-- друга, и ждать им нечего.
--
-- Хуже, чем неудобство. `delete-account` отказывает, пока у человека есть
-- бронь в `pending_approval`, `confirmed` или `active`. Значит застрявшая
-- бронь НАВСЕГДА закрывает обеим сторонам возможность удалить учётную
-- запись — то есть право, которое политика конфиденциальности обещает
-- отдельной строкой.
--
-- ЧЕГО МЫ НЕ ЗНАЕМ И НЕ ПРИТВОРЯЕМСЯ, ЧТО ЗНАЕМ. Продукт не видит момента
-- фактического возврата: он видит только то, что кто-то нажал кнопку.
-- Поэтому автоматическое закрытие не выдаёт себя за подтверждённый возврат,
-- а помечается отдельным столбцом. Запись честна для всякого, кто её
-- прочтёт: срок аренды истёк, возврат никто не подтвердил, бронь закрыта
-- временем.
--
-- Применять как остальные миграции проекта:
--   npx supabase db query --linked < supabase/migrations/20260813000020_auto_close_stuck_bookings.sql

ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS auto_closed_at timestamptz;

COMMENT ON COLUMN public.bookings.auto_closed_at IS
  'Проставляется, когда бронь закрыл ТАЙМЕР, а не человек. NULL — состояние подтверждено стороной сделки. Отличать обязательно: платформа не знает момента фактического возврата и не вправе выдавать своё закрытие за подтверждённый возврат.';

