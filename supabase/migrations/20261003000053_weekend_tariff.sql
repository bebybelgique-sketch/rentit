-- =============================================
-- 53. Тариф «выходные»
-- =============================================
--
-- ЗАЧЕМ. Прокат по выходным — главный случай для частного человека: в
-- субботу перекопать, в воскресенье вернуть. Прокатчики продают его
-- пакетом, и делают это одинаково (сверено 03.10.2026):
--
--   Boels (Бельгия): «samedi – lundi», до 48 часов — один дневной тариф;
--     «vendredi – lundi», до 72 часов — два.
--   Kiloutou: retrait vendredi 14–16 h, retour lundi 10–12 h — «louez 3
--     jours, payez 1 jour et demi».
--
-- Настоящее объявление 03.10 (мини-экскаватор, Валлония): 90 € день,
-- 350 € неделя, 150 € выходные. Последнее выразить в продукте было нечем:
-- трёхдневный пакет за 150 € удешевил бы и будние вторник–среду.
--
-- ПРАВИЛО (расчёт — supabase/functions/_shared/pricing.ts): пакет закрывает
-- отрезок брони внутри одного окна пятница–понедельник, содержащий субботу
-- и воскресенье: сб–вс, пт–вс, сб–пн, пт–пн. Цену назначает владелец.
--
-- Столбец необязателен: NULL — тарифа нет, расчёт как раньше. Ноль и
-- отрицательные запрещены, как у остальных тарифов (миграция 19): «0 € за
-- выходные» — опечатка или подарок, и владелец должен увидеть отказ.
--
-- Права: клиент пишет в items табличным грантом (храповик
-- scripts/migration-grants-allowlist.json) — новый столбец под ним, отдельная
-- выдача не нужна. browse_items перечисляет столбцы поимённо, и витрине
-- тариф выходных не нужен: его показывает страница вещи.
-- =============================================

ALTER TABLE public.items
  ADD COLUMN IF NOT EXISTS price_weekend numeric(10,2);

ALTER TABLE public.items
  DROP CONSTRAINT IF EXISTS items_price_weekend_positive;

ALTER TABLE public.items
  ADD CONSTRAINT items_price_weekend_positive CHECK (price_weekend IS NULL OR price_weekend > 0);

COMMENT ON COLUMN public.items.price_weekend IS
  'Цена за выходные, евро: отрезок брони внутри окна пт–пн, содержащий сб и вс (сб–вс, пт–вс, сб–пн, пт–пн). NULL — тарифа нет. Расчёт — supabase/functions/_shared/pricing.ts.';
