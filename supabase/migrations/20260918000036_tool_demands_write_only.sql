-- =============================================
-- Миграция 36: tool_demands действительно становится пишущей, а не читающей
-- =============================================
--
-- ЧТО Я СДЕЛАЛ НЕ ТАК В МИГРАЦИИ 34. Там написано «политики на чтение нет
-- НАМЕРЕННО… читает его только service_role», и выдан `grant insert`. Из
-- этого читается, будто клиент не имеет прав ни на что, кроме вставки. Это
-- неправда, и проверка сразу после выката это показала:
--
--   GET    /rest/v1/tool_demands  → 200 []      (а ожидался 42501)
--   PATCH  /rest/v1/tool_demands  → 204
--   DELETE /rest/v1/tool_demands  → 204
--
-- То есть у anon есть SELECT, UPDATE и DELETE. Пустой ответ давал не отказ в
-- правах, а RLS: политик на чтение, правку и удаление нет, поэтому строк не
-- видно и менять нечего.
--
-- ОТКУДА ПРАВА. Из умолчаний Supabase: в схеме public стоит
-- `alter default privileges … grant all on tables to anon, authenticated`.
-- Любая НОВАЯ таблица получает полный набор автоматически. `grant insert`
-- поверх этого не ограничивает ничего — он добавляет уже имеющееся.
--
-- Базовое состояние новой таблицы здесь — НЕ «прав нет», а «права есть все».
-- Поэтому единственный способ их сузить — сначала снять, потом выдать нужное.
--
-- ПОЧЕМУ ЭТО ВАЖНО, ЕСЛИ RLS И ТАК ДЕРЖИТ. По той же причине, по которой
-- вчера чинилась миграция 33 для bookings: защита стоит на одном рубеже
-- вместо двух, и стоит молча. Тот, кто завтра добавит узкую политику на
-- чтение — например «свои заявки видны автору», — получит вместе с ней
-- полный табличный SELECT и откроет список чужого спроса целиком. Ни один
-- тест при этом красным не станет.
--
-- Список названного спроса — это то, что люди сказали продукту, а не друг
-- другу. Читать его должен только service_role.
--
-- ПРОВЕРКА ПОСЛЕ ПРИМЕНЕНИЯ — теми же тремя запросами:
--   GET    → 42501 permission denied for table tool_demands
--   PATCH  → 42501
--   DELETE → 42501
--   POST   → 201 (вставка обязана продолжать работать)
-- =============================================

revoke all on public.tool_demands from anon, authenticated;

-- Ровно одно право и ровно тем ролям, которым оно нужно: спрос называют до
-- регистрации, поэтому anon здесь не лишний.
grant insert on public.tool_demands to anon, authenticated;

-- Служебная роль читает журнал спроса; RLS её не касается, но табличные
-- права нужны и ей (тот же урок, что в миграции 29).
grant select, insert, update, delete on public.tool_demands to service_role;
