-- =============================================
-- RentIt: доставка как объявленная услуга владельца
--
-- ЗАЧЕМ ЭТА МИГРАЦИЯ СУЩЕСТВУЕТ
--
-- Прокатчик со складом зарабатывает не только арендой. У шведского
-- проката aux (Booqable) доставка вынесена отдельной строкой к корзине:
-- 796 kr в черте города, 1600 kr в пределах 20 км — 7-14% сверх чека,
-- который клиент выбирает сам. У нас этого нет нигде: владелец либо
-- пишет условие словами в описании, где его не видит ни заявка, ни
-- вторая сторона, либо не предлагает доставку вовсе.
--
-- ЧТО СТАНОВИТСЯ ИСТОЧНИКОМ ПРАВДЫ
--
-- Один: `items.delivery_fee`. Пусто — владелец не доставляет, и
-- арендатор не видит ни строчки про доставку. Заполнено — доставляет за
-- эту цену. Отдельного флага «включено» НЕТ намеренно: два поля рядом
-- расходятся (флаг стоит, цены нет — что показывать?), а сводить
-- разошедшиеся источники в один мы уже делали 17.08 для занятости.
-- Тумблер в форме — это интерфейс поверх одного поля, а не второе поле.
--
-- ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ
--
-- 1. ДВУХ ЗОН, как у шведов. У них склад и штатный водитель, две зоны —
--    их операционка. У одного владельца с одной машиной вторая зона —
--    поле, которое некому заполнить.
--
-- 2. РАСЧЁТА. Доставка НЕ входит в `bookings.total_price`: там цена
--    аренды из тарифов (`_shared/pricing.ts`), она уже показана в пяти
--    местах, и смешение сломало бы смысл существующей колонки. Как и с
--    платой за просрочку (20260813000019), платформа денег не держит:
--    это РАСКРЫТИЕ условия, стороны считаются при встрече.
--
-- 3. ФИЛЬТРА ВИТРИНЫ. `browse_items` и `items_busy_between` перечисляют
--    столбцы поимённо и новых не увидят — так и задумано. Доставка это
--    условие сделки, а не критерий поиска; при нуле состоявшихся броней
--    фильтр «только с доставкой» был бы угадыванием.
--
-- ПОЧЕМУ СНИМОК ЦЕНЫ В БРОНИ, А НЕ ССЫЛКА НА ВЕЩЬ
--
-- Владелец завтра поменяет цену доставки, а бронь — договорённость на
-- вчерашних условиях. Без снимка страница брони молча начнёт показывать
-- другое число обеим сторонам, и узнают они об этом при встрече.
--
-- ПРИМЕНЯТЬ: npx supabase db query --linked < этот_файл.sql
-- НЕ `supabase db push`: schema_migrations пуста для всех миграций,
-- push попытается прогнать историю заново и сломает базу.
-- =============================================

-- ---------------------------------------------
-- 1. Услуга на стороне вещи
--
-- Обе колонки необязательны, и существующие объявления получают NULL —
-- то есть «доставки нет». Ни одно объявление не меняет поведения, и ни
-- один владелец не обязан ничего открывать и настраивать.
-- ---------------------------------------------
ALTER TABLE public.items
  ADD COLUMN IF NOT EXISTS delivery_fee      numeric(10,2),
  ADD COLUMN IF NOT EXISTS delivery_radius_km int;

ALTER TABLE public.items
  DROP CONSTRAINT IF EXISTS items_delivery_fee_positive,
  DROP CONSTRAINT IF EXISTS items_delivery_radius_positive,
  DROP CONSTRAINT IF EXISTS items_delivery_radius_needs_fee;

-- Ноль запрещён, а не приводится к NULL молча: «0 € за доставку» — это
-- либо опечатка, либо подарок, и в обоих случаях владелец должен
-- увидеть отказ, а не обнаружить последствия в брони. Тот же приём, что
-- у тарифов на срок (20260813000019).
ALTER TABLE public.items
  ADD CONSTRAINT items_delivery_fee_positive
    CHECK (delivery_fee IS NULL OR delivery_fee > 0),
  ADD CONSTRAINT items_delivery_radius_positive
    CHECK (delivery_radius_km IS NULL OR delivery_radius_km > 0),
  -- Радиус без цены — обещание без услуги: показать его негде, потому
  -- что блок доставки рисуется по наличию цены. База не даёт создать
  -- состояние, которое интерфейс не умеет отобразить.
  ADD CONSTRAINT items_delivery_radius_needs_fee
    CHECK (delivery_radius_km IS NULL OR delivery_fee IS NOT NULL);

COMMENT ON COLUMN public.items.delivery_fee IS
  'Объявленная владельцем цена доставки, евро. NULL — владелец не доставляет, и это ЕДИНСТВЕННЫЙ признак включённости услуги. Платформа сумму НЕ считает и НЕ удерживает: расчёт между сторонами при встрече.';
COMMENT ON COLUMN public.items.delivery_radius_km IS
  'До скольких километров действует объявленная цена. NULL — владелец радиус не назвал. Требует непустой delivery_fee.';

-- ---------------------------------------------
-- 2. Выбор арендатора на стороне брони
--
-- delivery_fee здесь — СНИМОК цены на момент заявки, а не ссылка на
-- текущее значение вещи. Инвариант ниже держит пару согласованной:
-- попросили доставку — снимок обязан быть; не просили — снимка быть не
-- должно. Заявку создаёт только edge-функция request-rental сервисным
-- ключом (вставка из браузера закрыта в 20260328000009), она же и
-- заполняет обе колонки из вещи, а не из тела запроса.
-- ---------------------------------------------
ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS delivery_requested boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS delivery_fee       numeric(10,2);

ALTER TABLE public.bookings
  DROP CONSTRAINT IF EXISTS bookings_delivery_snapshot_consistent;

ALTER TABLE public.bookings
  ADD CONSTRAINT bookings_delivery_snapshot_consistent
    CHECK (delivery_requested = (delivery_fee IS NOT NULL));

COMMENT ON COLUMN public.bookings.delivery_requested IS
  'Арендатор попросил доставку при заявке. Существующие брони — false: доставки в продукте не было.';
COMMENT ON COLUMN public.bookings.delivery_fee IS
  'Снимок цены доставки на момент заявки, евро. Не пересчитывается: последующая правка цены у вещи не меняет условий уже созданной брони. В total_price НЕ входит — это отдельная услуга, деньги идут мимо платформы.';
