-- =============================================
-- 44. Номер телефона меняет только verify-phone
-- =============================================
--
-- Миграция 17 закрыла подделку кода (phone_otp) и оставила клиенту
-- колоночный UPDATE на phone. Политика "Users can update own safe fields"
-- пришпиливает phone_verified, но не phone. Отсюда путь в обход проверки:
--
--   1. подтвердить через verify-phone номер, которым владеешь;
--   2. PATCH /rest/v1/users?id=eq.<свой id>  {"phone": "<любой номер>"};
--   3. phone_verified остаётся true — значок «téléphone vérifié» стоит на
--      номере, который никто не проверял.
--
-- verify-phone сама сбрасывает подтверждение при смене номера (21.09), но
-- прямая запись мимо неё этого не делает.
--
-- Совместимость проверена по коду, а не предположена:
--   • номер вводится только в PhoneVerification → verify-phone, а она
--     работает служебным ключом и грантов клиента не касается;
--   • сохранение профиля пишет full_name и avatar_url (Profile.tsx), phone
--     не передаёт ни один вызов useUpdateProfile.
--
-- ПРОВЕРКА ПОСЛЕ ПРИМЕНЕНИЯ — поведением, в `npm run test:edge`:
--   вошедший PATCH users {phone} → 42501
-- =============================================

REVOKE UPDATE (phone) ON public.users FROM anon, authenticated;
