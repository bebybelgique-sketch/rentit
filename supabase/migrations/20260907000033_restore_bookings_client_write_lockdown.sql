-- =============================================
-- Миграция 33: клиенту возвращён запрет писать в bookings
-- =============================================
--
-- ЧТО ЧИНИМ. Миграция 20260905000027 выдала роли `authenticated`
-- табличные гранты INSERT и UPDATE на public.bookings. Оба разворачивают
-- решения, принятые раньше и записанные явно:
--
--   • INSERT запрещён миграцией 20260328000009: политика «Renters can
--     insert bookings» позволяла из браузера завести бронь с любой ценой,
--     любым статусом и любыми датами мимо серверной проверки занятости;
--   • UPDATE запрещён миграцией 20260811000012: политики владельца и
--     арендатора позволяли перевести бронь в completed одним запросом из
--     консоли — минуя передачу и возврат, и тем самым открыв себе право
--     на взаимный отзыв.
--
-- Ни то, ни другое комментарием в 27 не упомянуто: там сказано «гранты
-- лишь делают проверки политик достижимыми». Для items и reviews это
-- правда — у них политики есть. У bookings политик на запись НЕТ НИ
-- ОДНОЙ: обе снесены в 09 и 12. Грант на таблицу, к которой не осталось
-- политик, ничего не «делает достижимым» — он снимает второй рубеж и
-- ждёт того, кто однажды добавит узкую политику и получит вместе с ней
-- полный табличный грант.
--
-- ПОЧЕМУ ЭТО НЕ БЫЛО ЭКСПЛУАТИРУЕМО И ВСЁ РАВНО ЧИНИТСЯ. RLS на bookings
-- включён, политик на запись нет — значит любой INSERT и UPDATE из
-- браузера сейчас отклоняется. Дыры нет. Чинится потому, что защита
-- держалась на одном рубеже вместо двух, и держалась молча: ни один тест
-- и ни один гейт не заметил бы возврата политики.
--
-- ПОЧЕМУ ЭТО НИЧЕГО НЕ ЛОМАЕТ. Клиент в bookings не пишет вообще: во всём
-- src/ есть только `select` (useRentals, useRentalsAsOwner, ItemDetail).
-- Создание и переходы идут через edge-функции respond-to-request и
-- transition-booking под service_role, а он RLS и грантам не подчиняется
-- и права получил отдельно — миграция 20260905000029.
--
-- ЧТО ОСТАЁТСЯ ОТ 27 И ПОЧЕМУ. SELECT на items/bookings/reviews и
-- колоночные гранты на users — нужны и верны. INSERT/UPDATE/DELETE на
-- items и INSERT на reviews — под ними живые политики, клиент этими
-- путями действительно ходит.
--
-- ПРОВЕРКА ПОСЛЕ ПРИМЕНЕНИЯ:
--   select grantee, privilege_type
--     from information_schema.role_table_grants
--    where table_schema = 'public' and table_name = 'bookings'
--      and grantee in ('anon', 'authenticated');
--   -- ожидается: только SELECT, и только там, где он был.
-- =============================================

REVOKE INSERT, UPDATE ON public.bookings FROM authenticated;

-- anon этих прав не получал ни в 27, ни раньше. Строка стоит, чтобы
-- ответ на вопрос «а у анонима?» был в файле, а не в чьей-то памяти:
-- REVOKE несуществующего права — законный no-op.
REVOKE INSERT, UPDATE ON public.bookings FROM anon;
