-- =============================================
-- Миграция 39: счётчик попыток ввода кода из SMS
-- =============================================
--
-- ЗАЧЕМ. Код подтверждения — шесть цифр, живёт десять минут, и до сих пор
-- проверялся БЕЗ ограничения числа попыток. Миллион комбинаций звучит
-- внушительно ровно до арифметики: перебор идёт не человеком, а скриптом,
-- и каждый новый запрос кода даёт следующие десять минут на подбор. Второй
-- фактор, который можно перебирать бесконечно, вторым фактором не является.
--
-- Столбец служебный: клиенту он не виден и не пишется.
--   • SELECT у клиента — по СПИСКУ (миграция 28), и этого имени в списке
--     нет, значит колонка не читается;
--   • UPDATE у клиента — тоже по списку (миграция 17): full_name,
--     avatar_url, phone, village, lat, lng. Нового имени там нет.
-- Пишет его только verify-phone под service_role.
--
-- ПОЧЕМУ NOT NULL DEFAULT 0, А НЕ NULLABLE. «Попыток не было» и «ноль
-- попыток» — одно и то же состояние, и хранить его двумя способами значит
-- завести ветку `?? 0` в каждом месте чтения.
--
-- ПРОВЕРКА ПОСЛЕ ВЫКАТА (ключ anon — колонки быть не должно):
--   GET /rest/v1/users?select=phone_otp_attempts&limit=1  ->  401
-- =============================================

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS phone_otp_attempts integer NOT NULL DEFAULT 0;

COMMENT ON COLUMN public.users.phone_otp_attempts IS
  'Сколько раз подряд вводили неверный код. Сбрасывается при выдаче нового кода и при успешном подтверждении. Пишет только verify-phone под service_role.';
