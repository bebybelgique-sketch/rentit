import { spawnSync } from 'node:child_process'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Уборка после ВСЕГО прогона, а не только после каждого теста.
 *
 * ЗАЧЕМ. У каждого набора есть `afterEach`, который удаляет свою вещь. Он не
 * спасает, когда прогон падает ПОСЛЕ создания вещи: тогда объявление доезжает
 * до живой витрины и остаётся там. 11.08.2026 так доехали шесть штук, ради
 * чего и написан scripts/cleanup-e2e-items.mjs.
 *
 * Но запускать его полагалось РУКАМИ — сообщение в фикстурах так и говорит:
 * «Проверь витрину и добей». 19.09.2026 стало видно, чего это стоит: на
 * проде висела вещь «E2E безкоординат mu800vl5-2d9g», созданная тем же утром
 * в 06:20, и она была ЕДИНСТВЕННЫМ объявлением на витрине. Весь публичный
 * шоурум продукта — мусор оснастки. Заметили это не на витрине: лендинг стал
 * считать вещи вместо зашитого нуля и сказал «1 outil en ligne».
 *
 * Ручной шаг, который однажды не сделают, — дефект замысла, а не
 * забывчивость. Поэтому уборка переехала в globalTeardown: он отрабатывает и
 * после падения тестов, и после их пропуска.
 *
 * ЧЕГО ЭТО НЕ ЗАКРЫВАЕТ. Убийство процесса (Ctrl-C, kill) не даёт отработать
 * ничему внутри процесса. На этот случай остаётся тот же скрипт руками:
 *   node scripts/cleanup-e2e-items.mjs --apply
 *
 * ПОЧЕМУ НЕ МОЛЧА. Отказ уборки печатается громко и целиком. Урок из шапки
 * самого скрипта: шаг, обёрнутый в `|| true`, падал МОЛЧА, и никто не узнавал,
 * что уборки не было. Прогон при этом не роняем: тесты уже отработали, и
 * красный итог из-за уборки спрятал бы их собственный результат.
 */
export default function globalTeardown() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  const script = resolve(root, 'scripts', 'cleanup-e2e-items.mjs')

  console.log('\n▸ Уборка объявлений, оставленных прогоном')
  const run = spawnSync(process.execPath, [script, '--apply'], { cwd: root, encoding: 'utf8' })

  const out = `${run.stdout ?? ''}${run.stderr ?? ''}`.trim()
  if (out) console.log(out.split('\n').map((l) => `  ${l}`).join('\n'))

  if (run.status !== 0) {
    console.error(
      '\n  УБОРКА НЕ ОТРАБОТАЛА. Объявления могли остаться на живой витрине.\n' +
      '  Проверить и добить:  node scripts/cleanup-e2e-items.mjs --apply\n',
    )
  }
}
