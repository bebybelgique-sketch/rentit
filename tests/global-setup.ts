/**
 * Говорит вслух, КУДА сейчас будут писать сквозные проверки.
 *
 * ЗАЧЕМ. Набор создаёт настоящие объявления настоящей учёткой, а baseURL по
 * умолчанию — ПРОД. С 03.10.2026 CI гоняет набор на стенде rentit-staging
 * (сайт собирается с ключами стенда и поднимается локально, см.
 * .github/workflows/gates.yml), а прод проверяет только чтением. Но запуск
 * руками без E2E_BASE_URL по-прежнему пишет в прод, и запрещать его нельзя.
 *
 * Чего нельзя иначе — так это писать в живую витрину МОЛЧА. Между «запустил
 * тесты» и «завёл объявление на проде» не должно быть ни одного шага,
 * который человек не видит. Поэтому адрес печатается крупно и до первого
 * теста, а не прячется в конфиге.
 */
export default function globalSetup() {
  const target = process.env.E2E_BASE_URL || 'https://rentit-plum.vercel.app'
  const isProd = !/localhost|127\.0\.0\.1/.test(target)
  // Только чтение: учёток нет, сценарии с записью пропускают себя сами.
  // Так CI проверяет прод после мержа (задание prod-smoke).
  const readOnly = process.env.E2E_READ_ONLY === '1'

  console.log('\n────────────────────────────────────────────────')
  if (readOnly) {
    console.log(`  Сквозные проверки ТОЛЬКО ЧИТАЮТ: ${target}`)
    console.log('────────────────────────────────────────────────\n')
    return
  }
  console.log(`  Сквозные проверки пишут в: ${target}`)
  if (isProd) {
    console.log('  Это ЖИВОЕ развёртывание: объявления будут настоящими.')
    console.log('  Другой адрес — переменной E2E_BASE_URL.')
  }
  console.log('  Уборка после прогона: tests/global-teardown.ts')
  console.log('────────────────────────────────────────────────\n')
}
