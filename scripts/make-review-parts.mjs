// Собирает задания для разбора по частям: одна страница — один файл,
// внутри уже отрисованный текст с десктопа и телефона.
//
// Почему так. Qwen 11.08 не смог осмотреть живой сайт: он тянет сырой
// HTML, а приложение — клиентский SPA, и на каждом маршруте ему приходит
// одна и та же пустая оболочка. Не сумев ничего увидеть, он выдал
// вымышленную находку в формате отчёта. Поэтому содержимое приносим мы,
// а его дело — рассуждать над тем, что действительно на экране.
//
// Запуск: node scripts/capture-pages.mjs && node scripts/make-review-parts.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CAP = join(root, 'capture');
const OUT = join(root, 'capture', 'parts');

const PARTS = [
  { n: 1, page: 'landing', title: 'Первый экран (лендинг)' },
  { n: 2, page: 'browse', title: 'Витрина и поиск' },
  { n: 3, page: 'terms', title: 'Условия использования' },
  { n: 4, page: 'privacy', title: 'Политика конфиденциальности' },
  { n: 5, page: 'login', title: 'Вход и регистрация' },
];

const RULES = `## Правила разбора

Ищем **противоречие между тем, что написано, и тем, что есть на самом деле**.

Про продукт, чтобы было с чем сверять:
- платформа НЕ принимает и не держит денег: расчёт наличными между людьми;
- платформа НЕ страхует и не покрывает ущерб;
- комиссии нет (сегодня; в будущем возможны платные опции — это честно);
- переписка идёт внутри брони, WhatsApp не используется;
- телефон второй стороны раскрывается только после подтверждённой брони;
- витрина пуста НАМЕРЕННО: 26 сгенерированных объявлений удалены. Пустота
  не дефект. Дефект — если она объяснена неверно или ведёт в тупик;
- регион — Брабант-Валлон, валюта евро, языки FR / EN / NL, основной FR.

Что считается находкой:
1. Утверждение, противоречащее списку выше.
2. Число, взятое из ниоткуда (количество вещей, средний рейтинг, время ответа).
3. Расхождение между страницами: лендинг говорит одно, условия другое.
4. Тупик: непонятно, что делать дальше.
5. Смешение языков на одном экране, потерянные подстановки \`{{...}}\`.

Что находкой НЕ считается: «слишком тёмный», «hero длинный», «мало
объявлений», предложения переписать раздел целиком. Это вкус, и я его не беру.

## Формат ответа

По одной находке, строго так:

\`\`\`
ЦИТАТА:   точная строка из текста ниже
ПОЧЕМУ:   какому факту о продукте противоречит
ЭКРАН:    десктоп / телефон / оба
\`\`\`

Если находок нет — так и написать. **Не додумывать то, чего нет в тексте:**
ты видишь ровно то, что приведено ниже, и ничего больше. Догадка,
оформленная как наблюдение, дороже пустого ответа — её приходится
проверять как настоящую.
`;

mkdirSync(OUT, { recursive: true });

for (const p of PARTS) {
  const read = (view) => {
    try {
      const raw = readFileSync(join(CAP, `${p.page}-${view}.txt`), 'utf8');
      return raw.split('\n').slice(2).join('\n').trim();
    } catch { return '(не снято)'; }
  };

  const desktop = read('desktop');
  const mobile = read('mobile');
  const same = desktop === mobile;

  const body = `# RentIt — разбор, часть ${p.n} из ${PARTS.length}: ${p.title}

Это ${p.n}-я часть. Разбирается **только она** — остальные страницы придут
отдельно. Не пытаться открыть сайт: содержимое приведено ниже целиком,
оно снято с живого адреса после отрисовки.

${RULES}

---

## Видимый текст — десктоп (1280px)

\`\`\`
${desktop}
\`\`\`

${same
  ? '## Телефон (390px)\n\nТекст совпадает с десктопным полностью.'
  : `## Видимый текст — телефон (390px)\n\n\`\`\`\n${mobile}\n\`\`\``}
`;

  const file = join(OUT, `часть-${p.n}-${p.page}.md`);
  writeFileSync(file, body);
  console.log(`часть ${p.n}: ${p.page.padEnd(9)} десктоп ${desktop.length} симв, телефон ${mobile.length} симв${same ? ' (одинаково)' : ''}`);
}

console.log(`\nГотово: ${PARTS.length} частей в capture/parts/`);
